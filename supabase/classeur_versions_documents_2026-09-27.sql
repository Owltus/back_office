select 'table classeur_document_versions, RLS activee' as controle,
       ((select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace
          where n.nspname = 'public' and c.relname = 'classeur_document_versions' and c.relrowsecurity) = 1)::text as ok
union all
select 'une seule policy, en lecture',
       ((select count(*) from pg_policies where tablename = 'classeur_document_versions') = 1
        and (select count(*) from pg_policies where tablename = 'classeur_document_versions' and cmd = 'SELECT') = 1)::text
union all
select 'authenticated : select seul ; anon : rien',
       ((select string_agg(privilege_type, ',' order by privilege_type) from information_schema.role_table_grants
          where grantee = 'authenticated' and table_schema = 'public' and table_name = 'classeur_document_versions') = 'SELECT'
        and (select count(*) from information_schema.role_table_grants
          where grantee = 'anon' and table_schema = 'public' and table_name = 'classeur_document_versions') = 0)::text
union all
select 'trigger pose sur classeur_documents',
       ((select count(*) from pg_trigger t join pg_class c on c.oid = t.tgrelid
          where c.relname = 'classeur_documents' and t.tgname = 'classeur_document_version' and not t.tgisinternal) = 1)::text
union all
select 'fonction trigger definer dans private, fermee a authenticated',
       ((select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
          where n.nspname = 'private' and p.proname = 'classeur_document_version' and p.prosecdef
            and not has_function_privilege('authenticated', p.oid, 'execute')) = 1)::text;
