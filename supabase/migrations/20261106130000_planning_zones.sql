-- Les ZONES de l'établissement (2026-11-06, lot 2, A5 du plan
-- planning-moteur-configurable : « qu'aucun paramètre ne soit en dur »).
--
-- 1. Table `planning_zones` : un ensemble de postes tenu ensemble, avec son
--    tableau (un chiffre par jour et par moment), tenu en continu ou non,
--    sa relève, sa passation avec la nuit, sa tolérance d'équipe. Zone 1
--    « Accueil » créée avec les réglages d'aujourd'hui.
-- 2. `planning_postes.zone_id` (nullable) : remplace `presence` et
--    `accueil_nuit` au calcul ; rempli à 1 pour les postes de l'accueil.
--    Les deux colonnes sont GARDÉES, plus lues.
-- 3. `planning_consignes.zone_id` : chaque chiffre du tableau appartient à
--    une zone ; clé unique (zone, jour, moment).
--
-- RETIRE (livraison : `--supprimer`) : la clé unique
-- `planning_consignes_unique` (jour, moment), remplacée par
-- (zone, jour, moment).
-- ÉCRIT DU CONTENU (livraison : `--avec-donnees`) : la zone 1, les zones des
-- postes et des consignes.

create table public.planning_zones (
  id bigint generated by default as identity primary key,
  nom text not null check (length(btrim(nom)) between 1 and 40),
  ordre integer not null default 0,
  continue boolean not null default true,
  releve_minutes integer not null default 30 check (releve_minutes between 0 and 240),
  passation_nuit boolean not null default true,
  equipe_tolerance integer not null default 30 check (equipe_tolerance between 0 and 240),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint planning_zones_nom_unique unique (nom)
);
comment on table public.planning_zones is
  'Zones de l''établissement : des postes tenus ensemble, avec leur tableau (un chiffre par jour et par moment). Tenue en continu : aucun trou d''une équipe à l''autre, d''un veilleur à l''autre. Relève, passation avec la nuit et tolérance d''équipe propres à la zone.';

create trigger planning_zones_stamp before insert or update on public.planning_zones
  for each row execute function private.planning_stamp();

alter table public.planning_zones enable row level security;

create policy "planning_zones read (page:planning)" on public.planning_zones
  for select to authenticated using ((select private.planning_niveau()) >= 1);
create policy "planning_zones insert (page:planning)" on public.planning_zones
  for insert to authenticated with check ((select private.planning_niveau()) >= 3);
create policy "planning_zones update (page:planning)" on public.planning_zones
  for update to authenticated using ((select private.planning_niveau()) >= 3)
  with check ((select private.planning_niveau()) >= 3);
create policy "planning_zones delete (page:planning)" on public.planning_zones
  for delete to authenticated using ((select private.planning_niveau()) >= 3);

grant select, insert, update, delete on public.planning_zones to authenticated;
grant all on public.planning_zones to service_role;

-- La zone de l'accueil, aux réglages d'aujourd'hui.
insert into public.planning_zones (id, nom, ordre, continue, releve_minutes, passation_nuit, equipe_tolerance)
select 1, 'Accueil', 0, true,
  coalesce((select releve_minutes from public.planning_reglages where id = 1), 30),
  coalesce((select passation_veilleur from public.planning_reglages where id = 1), true),
  coalesce((select equipe_tolerance from public.planning_reglages where id = 1), 30);
select setval(pg_get_serial_sequence('public.planning_zones', 'id'), 1);

-- Les postes de l'accueil (matin et soir, ou nuit) sont de la zone 1.
alter table public.planning_postes
  add column zone_id bigint references public.planning_zones (id) on delete set null;
update public.planning_postes set zone_id = 1 where presence or coalesce(accueil_nuit, false);
create index planning_postes_zone_idx on public.planning_postes (zone_id);

-- Chaque chiffre du tableau appartient à une zone.
alter table public.planning_consignes
  add column zone_id bigint not null default 1
  references public.planning_zones (id) on delete cascade;
alter table public.planning_consignes drop constraint planning_consignes_unique;
alter table public.planning_consignes
  add constraint planning_consignes_unique unique (zone_id, jour, periode);
alter table public.planning_consignes alter column zone_id drop default;
