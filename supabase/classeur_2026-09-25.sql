-- 3) Le niveau effectif : UNE fonction, source de vérité ------------------------
-- Calcul À PARTIR DES VALEURS DE LA LIGNE : la policy de lecture de
-- `classeur_classeurs` l'appelle avec les colonnes de la ligne elle-même.
-- Une création relit la ligne insérée (`insert … returning`), invisible à
-- une recherche par identifiant pendant l'insertion : chercher la ligne par
-- `id` refusait toute création (trouvé à la répétition du 2026-09-28).
create or replace function private.classeur_niveau_de(
  p_classeur_id bigint, p_created_by uuid, p_acces_tous text)
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_page   text := private.get_page_level('classeur');
  v_uid    uuid := auth.uid();
  v_droit  text;
begin
  if v_page is null then
    return 'aucun';
  end if;
  if v_page = 'gestion' then
    return 'gestion';
  end if;
  v_droit := coalesce(
    (select a.niveau from public.classeur_acces a
      where a.classeur_id = p_classeur_id and a.user_id = v_uid),
    case when p_created_by = v_uid then 'ecriture' end,
    p_acces_tous);
  if v_droit is null or v_droit = 'aucun' then
    return 'aucun';
  end if;
  -- Plafond : le droit de page borne le droit sur le classeur.
  if v_page = 'lecture' then
    return 'lecture';
  end if;
  if v_page = 'ecriture' then
    return v_droit;
  end if;
  return 'aucun';
end;
$$;

