with tables as (
  select unnest(array[
    'classeur_classeurs', 'classeur_chapters', 'classeur_periodicites',
    'classeur_documents', 'classeur_tracking_sheets',
    'classeur_signature_sheets', 'classeur_intercalaires',
    'classeur_merge_history'
