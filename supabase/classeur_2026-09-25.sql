-- Application : `supabase db query --linked -f supabase/classeur_2026-09-25.sql`
-- AUTORITÉ UNIQUE pour toutes les tables `classeur_*` : rejouable (idempotent),
-- à faire évoluer ICI (jamais de DDL à la volée).
--
-- Contexte : Registre stockait ces données dans un SQLite local (7 tables +
--   historique de fusion). Le Back Office les porte dans Postgres avec les
--   pratiques du projet : RLS par page à trois niveaux, estampillage d'auteur
--   par trigger via private.keep_author, aucun privilège pour anon, aucune
--   fonction security definer dans public.
--
-- Modèle :
--   classeur_classeurs        conteneur (nom, icône Lucide, établissement)
--   classeur_chapters         chapitre d'un classeur
--   classeur_periodicites     référentiel des périodicités de suivi (seed)
--   classeur_documents        document Markdown d'un chapitre
--   classeur_tracking_sheets  feuille de suivi périodique
--   classeur_signature_sheets feuille d'émargement (N lignes)
--   classeur_intercalaires    page de séparation
--   classeur_merge_history    instantanés JSON pris avant chaque fusion
--
-- Droits (plan/page-classeur/00-INDEX.md) :
--   lecture  (rang 1) : tout lire, imprimer.
--   ecriture (rang 2) : créer, modifier, réordonner, supprimer (douce),
--                       importer, fusionner (insert dans l'historique).
--   gestion           : suppression PHYSIQUE d'un classeur ou d'une entrée
--                       d'historique (tout le reste est une suppression douce
--                       = update de deleted_at).
--   Aucune fenêtre de grâce : un classeur réglementaire n'a pas de « jour ».
--
-- Innocuité : create table if not exists, create or replace, drop policy if
--   exists puis create. Ne touche à aucune table existante. Aucune donnée
--   réécrite. Le seed des périodicités est protégé par `on conflict do nothing`
--   sur le libellé.
--
-- Vérification : section finale (lecture seule), tout doit être `true`.
-- =============================================================================

