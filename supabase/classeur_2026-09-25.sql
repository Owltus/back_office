)
select controle, ok::text from (
  select 1 as n, '8 tables presentes' as controle,
    (select count(*) from pg_tables p join tables on p.tablename = tables.t where p.schemaname = 'public') = 8 as ok
  union all
  select 2, 'RLS activee sur les 8',
    (select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace join tables on c.relname = tables.t
      where n.nspname = 'public' and c.relrowsecurity) = 8
  union all
  select 3, 'aucune policy to public sur classeur_*',
    (select count(*) from pg_policies where schemaname = 'public' and tablename like 'classeur\_%' and 'public' = any(roles)) = 0
  union all
  select 4, '8 policies read + 12 insert/update + 3 delete/insert historique = 23',
    (select count(*) from pg_policies where schemaname = 'public' and tablename like 'classeur\_%') = 23
  union all
  select 5, 'trigger classeur_stamp pose 7 fois (+ taille sur l historique)',
    (select count(*) from pg_trigger where tgname = 'classeur_stamp' and not tgisinternal) = 7
  union all
  select 6, 'classeur_stamp non executable par anon/authenticated/public',
    not has_function_privilege('anon', 'public.classeur_stamp()', 'execute')
    and not has_function_privilege('authenticated', 'public.classeur_stamp()', 'execute')
  union all
  select 7, 'anon sans privilege sur les 8 tables',
    (select count(*) from information_schema.role_table_grants g join tables on g.table_name = tables.t
      where g.grantee = 'anon' and g.table_schema = 'public') = 0
  union all
  select 8, '9 periodicites',
    (select count(*) from public.classeur_periodicites) = 9
  union all
  select 9, 'aucune fonction security definer classeur_* dans public',
    (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public' and p.proname like 'classeur\_%' and p.prosecdef) = 0
) v order by n;
