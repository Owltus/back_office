       ((select count(*) from pg_policies where tablename = 'classeur_images') = 3
        and (select count(*) from pg_policies where tablename = 'classeur_images' and cmd = 'DELETE') = 0)::text
union all
select 'insert/update par proprietaire',
       ((select count(*) from pg_policies where tablename = 'classeur_images'
           and cmd in ('INSERT', 'UPDATE')
           and (coalesce(qual, '') || coalesce(with_check, '')) like '%classeur_write_ok%') = 2)::text
union all
select 'trigger classeur_stamp pose',
       ((select count(*) from pg_trigger t join pg_class c on c.oid = t.tgrelid
          where c.relname = 'classeur_images' and t.tgname = 'classeur_stamp' and not t.tgisinternal) = 1)::text
union all
select 'anon sans privilege',
       ((select count(*) from information_schema.role_table_grants
          where grantee = 'anon' and table_schema = 'public' and table_name = 'classeur_images') = 0)::text
