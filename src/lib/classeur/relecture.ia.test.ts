describe('quatrième mur — la liste fermée', () => {
  it('chaque expression a son exemple, et chaque exemple est détecté', () => {
    expect(EXEMPLES).toHaveLength(EXPRESSIONS_IA.length)
    EXPRESSIONS_IA.forEach((e, i) => {
      const re = new RegExp(`(?<![a-z0-9])(?:${e})(?![a-z0-9])`)
      expect(
        re.test(normaliserPhrase(EXEMPLES[i])),
        `${e} ← ${EXEMPLES[i]}`,
      ).toBe(true)
      expect(contientPhraseIa(EXEMPLES[i]), EXEMPLES[i]).toBe(true)
    })
  })

  it('les phrases légitimes d’une procédure ne déclenchent rien', () => {
    for (const p of LEGITIMES) expect(contientPhraseIa(p), p).toBe(false)
  })

  it('insensible à la casse et aux accents, apostrophes typographiques comprises', () => {
    for (const p of [
      'GÉNÉRÉ PAR L’IA',
      'genere par l ia'.replace('l ia', "l'ia"),
      'Généré Par Une IA',
      'brouillon généré',
      'BROUILLON GÉNÉRÉ',
      'Rédigé par **ChatGPT**',
      'En tant qu’intelligence artificielle',
      'JE PEUX ME TROMPER',
    ])
      expect(contientPhraseIa(p), p).toBe(true)
  })

  it('un mot entier : « ia » dans « via », « média » ne compte pas', () => {
    expect(contientPhraseIa('Généré par le média local')).toBe(false)
    expect(contientPhraseIa('généré par iamoteur')).toBe(false)
  })
})

describe('quatrième mur — dans le texte d’un document', () => {
  it('une alerte sur la ligne, à l’import comme dans l’éditeur', () => {
    const md =
      '# Accueil\n\nAccueillir le client.\n\n*Généré par IA, à relire.*'
    for (const contexte of ['import', 'editeur'] as const) {
      const a = alertesRelecture(md, null, null, contexte).filter(
        (x) => x.message === MESSAGE_IA,
      )
      expect(a).toEqual([{ ligne: 5, message: MESSAGE_IA }])
    }
  })

  it('une phrase coupée par un retour simple (un seul paragraphe imprimé)', () => {
    // Aucune des deux lignes seule ne suffit.
    expect(contientPhraseIa('Ce texte a été généré')).toBe(false)
    expect(contientPhraseIa('par une IA.')).toBe(false)
    const a = alertesRelecture('Ce texte a été généré\npar une IA.', null)
    expect(a.filter((x) => x.message === MESSAGE_IA)).toEqual([
      { ligne: 1, message: MESSAGE_IA },
    ])
    // Pas à travers une ligne vide (deux paragraphes).
    expect(
      alertesRelecture('Ce texte a été généré\n\npar une IA.', null).filter(
        (x) => x.message === MESSAGE_IA,
      ),
    ).toEqual([])
  })

  it('les blocs de code sont ignorés', () => {
    const md = '```\nGénéré par IA\n```\n\nRien à signaler.'
    expect(
      alertesRelecture(md, null).filter((x) => x.message === MESSAGE_IA),
    ).toEqual([])
  })

  it('le message est celui de la décision, sans tiret cadratin ni guillemets', () => {
    expect(MESSAGE_IA).toBe(
      "Phrase sur l'IA dans le texte. Elle serait imprimée.",
    )
  })
})

describe('quatrième mur — titres et descriptions de toutes les natures', () => {
  const avec = (champ: 'title' | 'description', texte: string) => ({
    title: champ === 'title' ? texte : 'Relevé',
    description: champ === 'description' ? texte : '',
    content: '',
  })

  it.each([
    'document',
    'tracking_sheet',
    'signature_sheet',
    'intercalaire',
    'chapter',
  ])(
    '%s : titre et description relus (création, modification, restauration)',
    (kind) => {
      for (const genre of [
        'creation',
        'modification',
        'restauration',
        'chapitre',
      ]) {
        if (genre === 'chapitre' && kind !== 'chapter') continue
        for (const exemple of EXEMPLES) {
          expect(
            relireLigneImport(
              { kind, genre, apres: avec('title', exemple) },
              null,
            ),
          ).toContainEqual({ ligne: 1, champ: 'titre', message: MESSAGE_IA })
          expect(
            relireLigneImport(
              { kind, genre, apres: avec('description', exemple) },
              null,
            ),
          ).toContainEqual({
            ligne: 1,
            champ: 'description',
            message: MESSAGE_IA,
          })
        }
      }
    },
  )

  it('le texte d’un document est relu en plus de ses champs', () => {
    expect(
      relireLigneImport(
        {
          kind: 'document',
          genre: 'creation',
          apres: {
            title: 'Accueil',
            description: '',
            content: 'Ceci est un brouillon.',
          },
        },
        null,
      ),
    ).toEqual([{ ligne: 1, message: MESSAGE_IA }])
  })

  it('une suppression n’est pas relue (rien ne sera imprimé)', () => {
    expect(
      relireLigneImport(
        {
          kind: 'document',
          genre: 'suppression',
          apres: avec('title', EXEMPLES[0]),
        },
        null,
      ),
    ).toBeNull()
  })

  it('alertesChampsIa : rien sur des champs légitimes', () => {
    for (const p of LEGITIMES)
      expect(alertesChampsIa({ title: p, description: p })).toEqual([])
  })
})

describe('relireFichierImport (D7 : import en nouveau classeur)', () => {
  it('chapitres et éléments à points à vérifier, dans l’ordre du fichier', () => {
    const r = relireFichierImport({
      chapters: [
        {
          label: 'Sécurité',
          description: 'Généré par IA',
          items: [
            {
              kind: 'document',
              title: 'Propre',
              description: '',
              content: 'Rien.',
            },
            {
              kind: 'signature_sheet',
              title: 'Émargement (brouillon)',
              description: '',
            },
            {
              kind: 'document',
              title: 'Évacuation',
              description: '',
              content: '# A\n### B',
            },
          ],
        },
      ],
    })
    expect(r.map((x) => [x.kind, x.titre, x.alertes.length])).toEqual([
      ['chapter', 'Sécurité', 1],
      ['signature_sheet', 'Émargement (brouillon)', 1],
      ['document', 'Évacuation', 1],
    ])
    expect(r[2].alertes[0].message).toMatch(/Titre sauté/)
  })

  it('un fichier propre : rien', () => {
    expect(
      relireFichierImport({
        chapters: [
          {
            label: 'A',
            description: '',
            items: [{ kind: 'tracking_sheet', title: 'Relevé' }],
          },
        ],
      }),
    ).toEqual([])
  })
})
