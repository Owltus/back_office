import { describe, expect, it } from 'vitest'

import {
  EXPRESSIONS_IA,
  MESSAGE_IA,
  alertesChampsIa,
  alertesRelecture,
  contientPhraseIa,
  normaliserPhrase,
  relireFichierImport,
  relireLigneImport,
} from '#/lib/classeur/relecture.ts'

/*
 * Relecture du « quatrième mur » (étape 7 du plan
 * `classeur-echange-ia-2026-10-19`, D9) : une phrase sur l'IA ou sur le
 * texte lui-même serait imprimée dans un registre. Oracles posés à la main :
 *   - chaque expression de la liste FERMÉE a au moins un exemple, détecté
 *     dans un titre, une description et un texte, avec ou sans accents et
 *     majuscules ;
 *   - des phrases LÉGITIMES d'une procédure (« à vérifier », « vérifier le
 *     contenu du coffre », « généré automatiquement », « en tant
 *     qu'assistant de direction »…) ne déclenchent rien. Le contrôle sur les
 *     107 documents réels de la base locale (lecture seule, 0 alerte) a été
 *     fait à part, sans recopier aucun contenu dans le dépôt.
 */

/** Un exemple réaliste par expression, dans l'ordre d'`EXPRESSIONS_IA`. */
